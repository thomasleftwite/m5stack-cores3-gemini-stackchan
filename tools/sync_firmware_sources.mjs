import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const firmware = path.join(root, 'firmware');
const entries = [];
function add(relative, file) {
  entries.push({ name: path.basename(relative), path: relative.replaceAll('\\', '/'), description: 'R13.2 / PC API確認・実機未検証', language: /\.[ch](pp)?$/.test(relative) ? 'cpp' : relative.endsWith('.json') ? 'json' : relative.endsWith('.md') ? 'markdown' : 'text', content: fs.readFileSync(file, 'utf8').replace(/^\uFEFF/, '') });
}
function walk(relative) {
  for (const item of fs.readdirSync(path.join(firmware, relative), { withFileTypes: true })) {
    const child = path.join(relative, item.name);
    if (item.isDirectory()) walk(child);
    else add(child, path.join(firmware, child));
  }
}
for (const name of fs.readdirSync(firmware).filter(n => n.endsWith('.md') || n === 'platformio.ini').sort()) add(name, path.join(firmware, name));
for (const directory of ['src', 'certs', 'tests', 'tools']) walk(directory);
add('data/config.example.json', path.join(firmware, 'data/config.example.json'));
for (const name of ['VOICE_PIPELINE_R13.md', 'R13_VALIDATION.md']) {
  const file = path.join(root, 'docs', name);
  if (fs.existsSync(file)) {
    fs.mkdirSync(path.join(firmware, 'docs'), { recursive: true });
    fs.copyFileSync(file, path.join(firmware, 'docs', name));
    add('docs/' + name, file);
  }
}
if (entries.some(e => /(^|\/)config\.json$/.test(e.path))) throw Error('Private config in distribution');
fs.writeFileSync(path.join(root, 'lib/firmware-sources.ts'), '// Generated by tools/sync_firmware_sources.mjs from firmware/.\nexport interface FirmwareFile { name: string; path: string; description: string; language: string; content: string; }\nexport const FIRMWARE_FILES: FirmwareFile[] = ' + JSON.stringify(entries, null, 2) + ';\n');
// Keep the historical root build sources consistent with the canonical firmware/ tree.
for (const dir of ['src', 'certs']) {
  fs.mkdirSync(path.join(root, dir), { recursive: true });
  for (const name of fs.readdirSync(path.join(firmware, dir))) fs.copyFileSync(path.join(firmware, dir, name), path.join(root, dir, name));
}
fs.copyFileSync(path.join(firmware, 'platformio.ini'), path.join(root, 'platformio.ini'));
fs.copyFileSync(path.join(firmware, 'data/config.example.json'), path.join(root, 'data/config.example.json'));
for (const entry of entries) {
  const file = entry.path.startsWith('docs/') ? path.join(root, entry.path) : path.join(firmware, entry.path);
  if (entry.content !== fs.readFileSync(file, 'utf8').replace(/^\uFEFF/, '')) throw Error('Source mismatch: ' + entry.path);
}
console.log('PASS: ' + entries.length + ' key-free distribution files match canonical sources; root mirrors synchronized');
